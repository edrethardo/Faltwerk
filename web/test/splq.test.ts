// .splq tests: TS parser + CPU mirror of the GPU dequantisation against the Python packer
// (make_viewer_data.pack_splq) and the float64 oracle p8_lib.apply_similarity (fixture: make_splq_fixture.py).
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { existsSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { evalSplq, parseSplq, SPLQ_FLAG_P16, SPLQ_FLAG_SIM, SPLQ_FLAG_SN, splqSn, splqSnWords } from '../src/splq.ts';

const FIX = join(dirname(fileURLToPath(import.meta.url)), 'fixtures');
const ref = JSON.parse(readFileSync(join(FIX, 'synth_splq.ref.json'), 'utf8'));

function load(name: string) {
  const b = readFileSync(join(FIX, `synth_${name}.splq`));
  return parseSplq(b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength));
}

for (const name of ['plain', 'sim']) {
  test(`splq ${name}: dequantisation (+ similarity) matches the Python oracle`, () => {
    const fr = load(name);
    assert.equal(fr.n, ref.n);
    assert.equal(!!(fr.flags & SPLQ_FLAG_SIM), name === 'sim');
    const exp = ref.cases[name];
    let worst = 0;
    for (let i = 0; i < fr.n; i++) {
      const [p, q, s, o, d] = evalSplq(fr, i);
      const cmp = (got: number[], want: number[], tol: number, what: string) => got.forEach((v, c) => {
        const e = Math.abs(v - want[c]);
        worst = Math.max(worst, e);
        assert.ok(e <= tol, `${name} splat ${i} ${what}[${c}]: ${v} vs ${want[c]}`);
      });
      cmp(p, exp.P[i], 2e-5, 'P');
      // q and -q are the same rotation
      const sgn = Math.sign(q.reduce((a, v, c) => a + v * exp.R[i][c], 0)) || 1;
      cmp(q.map((v) => v * sgn), exp.R[i], 2e-6, 'R');
      cmp(s, exp.S[i], 2e-6, 'S');
      cmp(o, [exp.O[i]], 1e-6, 'O');
      cmp(d, exp.D[i], 1e-6, 'D');
    }
    assert.ok(worst > 0 || name === 'plain');
  });
}

test('splq: rejects truncated and foreign buffers', () => {
  const b = readFileSync(join(FIX, 'synth_plain.splq'));
  const ab = b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength - 16);
  assert.throws(() => parseSplq(ab), /size/);
  assert.throws(() => parseSplq(new ArrayBuffer(300)), /not a \.splq/);
});

test('splq P16 + SN: 16-bit positions and SH bands match the Python packer', (t) => {
  if (!existsSync(join(FIX, 'synth_runsn.splq'))) return t.skip('fixture generated by bench/make_splq_fixture.py');
  const r = JSON.parse(readFileSync(join(FIX, 'synth_p16sn.ref.json'), 'utf8'));
  const fr = load('runsn');
  assert.equal(fr.n, r.n);
  assert.ok(fr.flags & SPLQ_FLAG_P16 && fr.flags & SPLQ_FLAG_SN);
  assert.equal(fr.snM, r.m);
  const words = splqSnWords(fr)!;
  assert.equal(words.length, fr.n * 12);
  for (let i = 0; i < fr.n; i++) {
    const [p] = evalSplq(fr, i);
    p.forEach((v, c) => assert.ok(Math.abs(v - r.P[i][c]) <= 2e-5 * Math.max(1, Math.abs(r.P[i][c])), `P ${i} ${c}: ${v} vs ${r.P[i][c]}`));
    for (let k = 0; k < 45; k++) {
      const want = k < r.m ? r.SN[i][k] : 0;
      assert.ok(Math.abs(splqSn(fr, i, k) - want) <= 1e-6, `SN ${i} ${k}`);
      assert.equal(new Uint8Array(words.buffer)[i * 48 + k], k < r.m ? fr.sn![i * fr.snStride + k] : 0);
    }
  }
  const b = readFileSync(join(FIX, 'synth_p16sn.splq'));
  assert.throws(() => parseSplq(b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength - 4)), /size/);
});
